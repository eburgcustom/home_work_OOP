
class PrintMixin:
    """Миксин, который при создании объекта выводит информацию о классе и параметрах."""

    def __init__(self, *args: object) -> None:
        """Инициализирует объект и выводит информацию о его создании.

        Args:
            *args: Аргументы, передаваемые в родительский класс.
        """
        print(f"Создан объект класса {self.__class__.__name__}{args}")
        super().__init__(*args)

    def __repr__(self) -> str:
        """Возвращает строковое представление объекта.

        Returns:
            Строковое представление объекта в формате ИмяКласса({атрибуты}).
        """
        return f"{self.__class__.__name__}({self.__dict__})"
